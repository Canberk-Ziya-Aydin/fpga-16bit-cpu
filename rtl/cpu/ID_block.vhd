entity ID_block is
    Port (
        adress_of_next_instruction_in : in STD_LOGIC_VECTOR (15 downto 0);
        raw_instruction : in STD_LOGIC_VECTOR (15 downto 0);

        --branch_available : out STD_LOGIC;
        --branch_target : out STD_LOGIC_VECTOR (15 downto 0);
        adress_of_next_instruction_out : out STD_LOGIC_VECTOR (15 downto 0);
        read_data1 : out STD_LOGIC_VECTOR (15 downto 0);
        read_data2 : out STD_LOGIC_VECTOR (15 downto 0);
        opcode : out STD_LOGIC_VECTOR (3 downto 0);
        rs2 : out STD_LOGIC_VECTOR (3 downto 0);
        imm8 : out STD_LOGIC_VECTOR (7 downto 0);
        imm12 : out STD_LOGIC_VECTOR (11 downto 0);
        rs1 : out STD_LOGIC_VECTOR (3 downto 0);
        rd : out STD_LOGIC_VECTOR (3 downto 0);

        --reg_rw : out STD_LOGIC;
        reg_adress1 : out STD_LOGIC_VECTOR (3 downto 0);
        reg_adress2 : out STD_LOGIC_VECTOR (3 downto 0);
        
        reg_read_data1 : in STD_LOGIC_VECTOR (15 downto 0);
        reg_read_data2 : in STD_LOGIC_VECTOR (15 downto 0);

        -- Information about the older instruction currently in EX.
        -- These inputs are used to detect a LOAD followed immediately by an
        -- instruction that consumes the loaded register.
        id_ex_opcode_in : in STD_LOGIC_VECTOR (3 downto 0);
        id_ex_rd_in : in STD_LOGIC_VECTOR (3 downto 0);

        -- Pipeline controls generated by the load-use hazard detector.
        pc_enable : out STD_LOGIC;
        if_id_enable : out STD_LOGIC;
        id_ex_flush : out STD_LOGIC
    );
end ID_block;

architecture Behavioral of ID_block is
    signal decoded_opcode : STD_LOGIC_VECTOR (3 downto 0);
    signal decoded_rd : STD_LOGIC_VECTOR (3 downto 0);
    signal decoded_rs1 : STD_LOGIC_VECTOR (3 downto 0);
    signal decoded_rs2 : STD_LOGIC_VECTOR (3 downto 0);
    signal selected_source_1 : STD_LOGIC_VECTOR (3 downto 0);
begin
    decoded_opcode <= raw_instruction(15 downto 12);
    decoded_rd     <= raw_instruction(11 downto 8);
    decoded_rs1    <= raw_instruction(7 downto 4);
    decoded_rs2    <= raw_instruction(3 downto 0);

    -- LIL and LIH preserve half of the old Rd value, so Rd is their actual
    -- first source register.  For all other instructions source 1 is rs1.
    selected_source_1 <= decoded_rd when
                         (decoded_opcode = "1000" or decoded_opcode = "1001")
                         else decoded_rs1;

    opcode <= decoded_opcode;
    rd     <= decoded_rd;
    rs1    <= selected_source_1;
    rs2    <= decoded_rs2;
    imm8   <= raw_instruction(7 downto 0);
    imm12  <= raw_instruction(11 downto 0);


    read_data1 <= reg_read_data1;
    read_data2 <= reg_read_data2;
    adress_of_next_instruction_out <= adress_of_next_instruction_in;

    reg_adress1 <= selected_source_1;
    reg_adress2 <= decoded_rs2;

process(decoded_opcode, selected_source_1, decoded_rs2,id_ex_opcode_in, id_ex_rd_in)
    variable rd1_smaller_then_rd2 : STD_LOGIC := '0';
    variable rd1_equals_rd2 : STD_LOGIC := '0';
    variable uses_source_1 : STD_LOGIC := '0';
    variable uses_source_2 : STD_LOGIC := '0';
    variable load_use_hazard : STD_LOGIC := '0';
begin
        uses_source_1 := '0';
        uses_source_2 := '0';
        load_use_hazard := '0';

        --if signed(reg_read_data2) > signed(reg_read_data1) then
        --    rd1_smaller_then_rd2 := '1';
        --else
        --    rd1_smaller_then_rd2 := '0';
        --end if;
        --if signed(reg_read_data1) = signed(reg_read_data2) then
        --    rd1_equals_rd2 := '1';
        --else
        --    rd1_equals_rd2 := '0';
        --end if;

        --if ((rd1_equals_rd2 = '1' and (decoded_opcode = "1100")) or
        --    (rd1_smaller_then_rd2 = '1' and (decoded_opcode = "1101"))) then
        --    branch_available <= '1';
        --else
         --   branch_available <= '0';
        --end if;

        --branch_target <= std_logic_vector(signed(adress_of_next_instruction_in) + shift_left(resize(signed(raw_instruction(11 downto 8)), 16), 1)); --if the command is brach 11 downto 8 stores offset


        -- Determine which register operands the instruction in ID genuinely
        -- consumes in EX.  This avoids false stalls caused by unused fields or
        -- by the immediate bits in LIL/LIH.
        if (decoded_opcode = "0001" or -- ADD
            decoded_opcode = "0010" or -- SUB
            decoded_opcode = "0011" or -- NAND
            decoded_opcode = "1011" or -- STORE
            decoded_opcode = "1110") then --CMP
            uses_source_1 := '1';
            uses_source_2 := '1';
        elsif (decoded_opcode = "0100" or -- SLL
               decoded_opcode = "0101" or -- SRL
               decoded_opcode = "0110" or -- SLA
               decoded_opcode = "0111" or -- SRA
               decoded_opcode = "1000" or -- LIL (old Rd is source 1)
               decoded_opcode = "1001" or -- LIH (old Rd is source 1)
               decoded_opcode = "1100" or -- Jump if equal
               decoded_opcode = "1101" or -- jump if signed less
               decoded_opcode = "1111" or -- unconditional jump
               decoded_opcode = "1010") then -- LOAD address
            uses_source_1 := '1';
        end if;

        -- A one-cycle stall is required when the instruction in EX is a LOAD
        -- and the instruction in ID needs the LOAD destination in its EX
        -- stage, including register targets for branches resolved in EX.
        if id_ex_opcode_in = "1010" then
            if ((uses_source_1 = '1' and id_ex_rd_in = selected_source_1) or
                (uses_source_2 = '1' and id_ex_rd_in = decoded_rs2)) then
                if id_ex_rd_in(3 downto 2) /= "11" then
                    load_use_hazard := '1';
                end if;
            end if;
        end if;

        pc_enable   <= not load_use_hazard;
        if_id_enable <= not load_use_hazard;
        id_ex_flush <= load_use_hazard;
end process;

end Behavioral;
